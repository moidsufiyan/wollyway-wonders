import { Router } from 'express';
import { createPaymentIntent, handleRazorpayWebhook } from '../controllers/payment.controller.js';
import { protect } from '../middlewares/auth.middleware.js';
import { validate } from '../middlewares/validate.js';
import { createPaymentIntentSchema } from '../validators/payment.validator.js';

const router = Router();

/**
 * @swagger
 * tags:
 *   name: Payments
 *   description: Payment gateway intents and verified webhook processing
 */

/**
 * @swagger
 * /api/v1/payments/create-intent:
 *   post:
 *     summary: Initialize or reuse gateway payment intent for active checkout session
 *     tags: [Payments]
 *     security:
 *       - bearerAuth: []
 *     requestBody:
 *       required: true
 *       content:
 *         application/json:
 *           schema:
 *             type: object
 *             required:
 *               - provider
 *             properties:
 *               provider:
 *                 type: string
 *                 enum: [razorpay, stripe]
 *                 example: razorpay
 *     responses:
 *       200:
 *         description: Payment intent successfully generated or reused
 *       400:
 *         description: Checkout session not in a payable state
 *       404:
 *         description: Active checkout session not found
 *       409:
 *         description: Reservation expired
 */
router.post('/create-intent', protect, validate(createPaymentIntentSchema), createPaymentIntent);

/**
 * @swagger
 * /api/v1/payments/webhook/razorpay:
 *   post:
 *     summary: Receive and process verified payment capture webhooks from Razorpay
 *     tags: [Payments]
 *     description: Public webhook boundary secured by cryptographic HMAC SHA256 signature verification
 *     parameters:
 *       - in: header
 *         name: x-razorpay-signature
 *         required: true
 *         schema:
 *           type: string
 *         description: HMAC SHA256 hex signature generated by Razorpay
 *     responses:
 *       200:
 *         description: Webhook event processed or duplicate absorbed
 *       400:
 *         description: Amount/currency reconciliation mismatch or bad payload
 *       401:
 *         description: Invalid webhook signature
 *       500:
 *         description: Internal error processing event (triggers gateway retry)
 */
router.post('/webhook/razorpay', handleRazorpayWebhook);

export default router;
